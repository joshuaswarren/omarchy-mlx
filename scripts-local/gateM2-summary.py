#!/usr/bin/env python3
"""Generate SUMMARY-m2.md from the run logs in
receipts/2026-10-07-release-0.7.31/gates-run/.

This is the only place SUMMARY-m2.md comes from; never hand-edited.
Run: python3 scripts-local/gateM2-summary.py <gates-run-dir> > SUMMARY-m2.md
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(
    "receipts/2026-10-07-release-0.7.31/gates-run"
)
WHEEL_VERSION = "0.32.4.dev202610071347+9b5c938"
WHEEL_SHA     = "a2f8c83e5c5f635d00702565a8557d87c40a9eccac885329dcec4692d85d300d"
VTAR_SHA      = "1cc390b1e25c55a80c8c21327a39d7e498cafb5144a75b0ff1fc9e6f8b54b074"
TAG_SHA       = "9b5c938fe236e767df9545de301cfc74fdbc3395"
MAIN_SHA      = "main: see gate-script commit log on origin"

def _read(name): return (ROOT / name).read_text()

def g1():
    log = _read("g1-install.log")
    wid = re.search(r"WHEEL_IDENTITY\s+installed=(\S+)\s+expected=(\S+)", log)
    installs = re.search(r"INSTALL_EXIT\s+(\d+)", log)
    launch   = re.search(r"LAUNCHER_HELP_EXIT\s+(\d+)", log)
    serve    = re.search(r"SERVE_ENTRY_EXIT\s+(\d+)", log)
    parak    = re.search(r"PARAKEET_LAUNCHER_HELP_EXIT\s+(\d+)", log)
    return {
        "wheel_logged": (wid.group(1) if wid else "?"),
        "wheel_expected": (wid.group(2) if wid else "?"),
        "install_exit": (installs.group(1) if installs else "?"),
        "launcher_exit": (launch.group(1) if launch else "?"),
        "serve_exit": (serve.group(1) if serve else "?"),
        "parakeet_exit": (parak.group(1) if parak else "?"),
        "pass": (wid and wid.group(1) == wid.group(2)
                 and installs.group(1) == "0"
                 and launch.group(1) == "0"
                 and serve.group(1) == "0"
                 and parak.group(1) == "0"),
    }

def g16(leg):
    raw = _read(f"g16-leg{leg}-jwm2.log")
    start = raw.find("{")
    obj = json.loads(raw[start:raw.rfind("}") + 1]) if start != -1 else {}
    p = obj.get("provenance", {})
    rc = re.search(rf"g16-leg{leg}_RC=(\d+)", raw)
    return {
        "wheel": p.get("wheel_version"),
        "libmlx_sha": p.get("libmlx_sha256"),
        "icd_json": p.get("icd_json"),
        "libvulkan_sha": p.get("libvulkan_sha256"),
        "uname": p.get("uname"),
        "pass": obj.get("pass"),
        "rc": rc.group(1) if rc else "?",
    }


def _redact_path(s: str) -> str:
    if not isinstance(s, str):
        return s
    return s.replace("/home/joshuawarren", "$HOME")

def g16b(leg):
    raw = _read(f"g16b-leg{leg}-jwm2.log")
    rc = re.search(rf"g16b-leg{leg}_RC=(\d+)", raw)
    last = next((l for l in reversed(raw.splitlines()) if l.strip()), "")
    return {"rc": rc.group(1) if rc else "?", "last_line": last}

def g7b():
    log = _read("g7b-system-install.log")
    sysinstall = re.search(r"SYSINSTALL_EXIT\s+(\d+)", log)
    install_tree = re.search(r"INSTALL_TREE\s+(\S+)\s+HEAD=(\S+)", log)
    staged = re.findall(r"STAGED_OK\s+(\S+)", log)
    missing = re.findall(r"STAGED_MISSING\s+(\S+)", log)
    return {
        "install_tree": install_tree.group(1) if install_tree else "?",
        "head": install_tree.group(2) if install_tree else "?",
        "sysinstall_exit": sysinstall.group(1) if sysinstall else "?",
        "staged_count": len(staged),
        "missing_count": len(missing),
        "pass": (sysinstall and sysinstall.group(1) == "0"
                 and install_tree.group(2) == TAG_SHA
                 and len(missing) == 0 and len(staged) == 7),
    }

def g17():
    raw = _read("g17-result.json")
    obj = json.loads(raw)
    results = obj.get("results", {})
    return {
        "pass": obj.get("pass"),
        "apply_script": obj.get("apply_script"),
        "results": {
            v: {"apply1": r.get("apply1_rc"), "apply2": r.get("apply2_rc"),
                "download": r.get("download_rc"), "pass": r.get("pass")}
            for v, r in results.items()
        },
    }

def main():
    g1_ = g1(); p = g16("P"); b = g16("B")
