    out.append("g1 fetched the `SHA256SUMS` from `MLX_OMARCHY_RELEASE_BASE=file://$ASSETS_DIR`;")
    out.append("the SHA256SUMS in `$HOME/v0730-assets/` was the v0.7.30-era file and named")
    out.append("`mlx_omarchy-0.32.4.dev202610070939+cf71ea2-…whl`, which install.sh then")
    out.append("fetched. Every gate that reused `$TAG-gate-home` (g2..g12, g14) therefore")
