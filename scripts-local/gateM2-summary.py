    out.append(f"| g16-qmm-batch leg P | {p['rc']} | {p['wheel']} | {p['libmlx_sha'][:12]} | `{_redact_path(p['icd_json'])}` | {p['libvulkan_sha'][:12]} | {'PASS' if p['pass'] else 'FAIL'} |")
    out.append(f"| g16b-qmm-route-probe leg P | {p16b['rc']} | (leg P) | (leg P) | (leg P) | (leg P) | {'PASS' if p16b['rc']=='0' else 'FAIL'} (last: {p16b['last_line'][:80]}) |")
