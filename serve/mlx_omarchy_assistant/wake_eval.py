"""Offline wake-word evaluation: score clip files through the shipped
WakeWordDetector, sweep the threshold and the RMS VAD pre-gate, and report
TPR/FPR so the listener's defaults are tuned on data instead of vibes.

Clips come from a manifest (file, variant, text, label) generated by
`receipts/2026-11-21-wake-eval-100/gen-clips.py` (espeak-ng, deterministic).
Each clip is scored once into a per-chunk (rms, score) curve with the real
session; the threshold/floor grid is then applied in pure post-processing
that mirrors the detector exactly: a chunk fires only when its score crosses
the threshold, its RMS passes the floor (the pre-gate suppresses scoring, so
gated chunks can never fire), and the 1.5 s refractory has elapsed.

CPU-only. Real openWakeWord inference is hardware-light and runs anywhere;
unit tests inject a scripted session instead.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

SAMPLE_RATE = 16000
MIN_SECONDS = 2.0  # pad short clips so the detector sees streaming context


def load_pcm(path: Path) -> bytes:
    """Read a clip as 16 kHz mono int16 PCM, padded to MIN_SECONDS.

    16 kHz mono files come through the stdlib wave module, so the tests
    need nothing beyond numpy. Other rates are resampled with
    soundfile/scipy — the generator's espeak output is 22.05 kHz.
    """
    import wave
    with wave.open(str(path), "rb") as handle:
        native = (handle.getnchannels() == 1
                  and handle.getsampwidth() == 2
                  and handle.getframerate() == SAMPLE_RATE)
        if native:
            pcm = handle.readframes(handle.getnframes())
        else:
            pcm = _resample_to_16k(path)
    need = int(MIN_SECONDS * SAMPLE_RATE) * 2  # bytes
    if len(pcm) < need:
        pcm = pcm + bytes(need - len(pcm))
    return pcm


def _resample_to_16k(path: Path) -> bytes:
    import numpy as np
    import soundfile as sf
    data, sr = sf.read(path, dtype="int16")
    if sr != SAMPLE_RATE:
        import scipy.signal as sig
        data = sig.resample_poly(data.astype("float64"), SAMPLE_RATE, sr)
        data = np.asarray(data, dtype="int16")
    return np.asarray(data, dtype="int16").tobytes()


def make_detector(model_path: str, threshold: float, vad_rms_floor: float):
    from mlx_omarchy_assistant import wake_word
    return wake_word.WakeWordDetector(
        model_path, threshold=threshold, vad_rms_floor=vad_rms_floor)


class RecordingSession:
    """Wraps the real session, recording each chunk's RMS and top score.

    Fed to a WakeWordDetector built with threshold high enough to never fire
    and vad_rms_floor 0, so one pass records the full curve for
    post-processing instead of one pass per grid point.
    """

    def __init__(self, inner):
        self.inner = inner
        self.rms: list[float] = []
        self.scores: list[float] = []

    def predict(self, pcm):
        import numpy as np
        samples = np.frombuffer(pcm, dtype=np.int16).astype(np.float64)
        self.rms.append(float(np.sqrt(np.mean(samples ** 2))))
        score = float(max(self.inner.predict(pcm).values()))
        self.scores.append(score)
        return {"recorded": score}

    def reset(self):
        self.rms.clear()
        self.scores.clear()


def clip_curve(pcm: bytes, detector) -> dict:
    """Score one clip into a (rms, scores) curve via a recording pass.

    Chunks are the listener's 80 ms step: CHUNK samples = CHUNK * 2 bytes.
    The detector is not reset here — the model is fresh per clip, and
    openwakeword's reset() is not a no-op on a fresh model (it changes the
    scores of the clip that follows).
    """
    session = RecordingSession(detector._session)
    detector._session = session
    step = detector_chunk() * 2
    for off in range(0, len(pcm), step):
        chunk = pcm[off:off + step]
        if len(chunk) < step:
            chunk = chunk + bytes(step - len(chunk))
        detector.process(chunk)
    detector._session = session.inner
    return {"rms": session.rms, "scores": session.scores}


_chunk_cache: list[int] = []


def detector_chunk() -> int:
    if not _chunk_cache:
        from mlx_omarchy_assistant import wake_word
        _chunk_cache.append(wake_word.CHUNK)
    return _chunk_cache[0]


def curve_row(curve: dict, threshold: float, floor: float,
              refractory_seconds: float = 1.5) -> dict:
    """Apply one (threshold, floor) point to a curve. Mirrors
    WakeWordDetector.process exactly: every chunk is scored (feeding the
    model keeps its feature timeline intact), a fire counts only when the
    chunk RMS clears the floor, and the refractory suppresses refires."""
    step = detector_chunk() / SAMPLE_RATE
    last_fire = float("-inf")
    peak = 0.0
    fired = False
    for i, score in enumerate(curve["scores"]):
        consumed = (i + 1) * step
        if score > peak:
            peak = score
        if score < threshold:
            continue
        if floor > 0.0 and curve["rms"][i] < floor:
            continue
        if consumed - last_fire < refractory_seconds:
            continue
        last_fire = consumed
        fired = True
    return {"fired": fired, "peak": round(peak, 4)}


def build_curves(manifest: list[dict], clips_dir: Path, model_path: str,
                 session=None) -> list[dict]:
    """Score every clip from a fresh model.

    openwakeword keeps cross-utterance state and its reset() does not clear
    it (measured: fresh 0.4305, after reset 0.4762, without reset 0.9572 on
    the same clip). One model per clip keeps every score independent of the
    clip before it, which is what the threshold table needs.
    """
    from mlx_omarchy_assistant import wake_word
    curves = []
    for entry in manifest:
        detector = wake_word.WakeWordDetector(
            model_path, threshold=0.999, vad_rms_floor=0.0, session=session)
        curve = clip_curve(load_pcm(clips_dir / entry["file"]), detector)
        curves.append({"file": entry["file"], "label": entry["label"], **curve})
    return curves


def curve_row_of(clip: dict, threshold: float, floor: float) -> dict:
    row = curve_row(clip, threshold, floor)
    fired, label = row["fired"], clip["label"]
    return {"file": clip["file"], "label": label, "fired": fired,
            "peak": row["peak"]}


def grid_row(curves: list[dict], threshold: float, floor: float) -> dict:
    tp = fp = tn = fn = 0
    for clip in curves:
        fired = curve_row_of(clip, threshold, floor)["fired"]
        if clip["label"] == "positive" and fired:
            tp += 1
        elif clip["label"] == "negative" and fired:
            fp += 1
        elif clip["label"] == "negative":
            tn += 1
        else:
            fn += 1
    n_pos, n_neg = tp + fn, fp + tn
    return {
        "threshold": threshold,
        "vad_rms_floor": floor,
        "tpr": round(tp / n_pos, 4) if n_pos else None,
        "fpr": round(fp / n_neg, 4) if n_neg else None,
        "tp": tp, "fn": fn, "fp": fp, "tn": tn,
    }


def sweep(curves: list[dict], thresholds: list[float],
          floors: list[float]) -> list[dict]:
    return [grid_row(curves, t, f) for t in thresholds for f in floors]


def direct_row(manifest: list[dict], clips_dir: Path, model_path: str,
               threshold: float, floor: float, session=None) -> dict:
    """Score every clip through the shipped detector and count the fires.

    This is the ground truth path: the real WakeWordDetector, the real
    chunking, a fresh model per clip (openwakeword keeps cross-utterance
    state and its reset() does not clear it).
    """
    from mlx_omarchy_assistant import wake_word
    step = detector_chunk() * 2
    tp = fp = tn = fn = 0
    for entry in manifest:
        detector = wake_word.WakeWordDetector(
            model_path, threshold=threshold, vad_rms_floor=floor, session=session)
        pcm = load_pcm(clips_dir / entry["file"])
        fired = False
        for off in range(0, len(pcm), step):
            piece = pcm[off:off + step]
            if len(piece) < step:
                piece = piece + bytes(step - len(piece))
            if detector.process(piece):
                fired = True
        if entry["label"] == "positive":
            tp, fn = (tp + 1, fn) if fired else (tp, fn + 1)
        else:
            fp, tn = (fp + 1, tn) if fired else (fp, tn + 1)
    n_pos, n_neg = tp + fn, fp + tn
    return {
        "threshold": threshold,
        "vad_rms_floor": floor,
        "tpr": round(tp / n_pos, 4) if n_pos else None,
        "fpr": round(fp / n_neg, 4) if n_neg else None,
        "tp": tp, "fn": fn, "fp": fp, "tn": tn,
    }


def direct_sweep(manifest: list[dict], clips_dir: Path, model_path: str,
                 thresholds: list[float], floors: list[float],
                 session=None) -> list[dict]:
    return [direct_row(manifest, clips_dir, model_path, t, f, session=session)
            for t in thresholds for f in floors]


def main(argv: list[str] | None = None, session=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--clips-dir", required=True, type=Path)
    parser.add_argument("--model", required=True)
    parser.add_argument("--thresholds", default="0.3,0.35,0.4,0.45,0.5,0.55,0.6")
    parser.add_argument("--floors", default="0,150,300,450,600")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--mode", choices=["direct", "curve"], default="direct",
                        help="direct: the shipped detector (ground truth); "
                             "curve: fast scan over recorded score curves")
    args = parser.parse_args(argv)

    manifest = json.loads(args.manifest.read_text())
    thresholds = [float(t) for t in args.thresholds.split(",")]
    floors = [float(f) for f in args.floors.split(",")]
    curves = []
    if args.mode == "direct":
        rows = direct_sweep(manifest, args.clips_dir, args.model,
                            thresholds, floors, session=session)
    else:
        curves = build_curves(manifest, args.clips_dir, args.model,
                              session=session)
        rows = sweep(curves, thresholds, floors)
    args.out.write_text(json.dumps(
        {"rows": rows, "curves": curves}, indent=1) + "\n")
    print(f"mode={args.mode}")
    print(f"{'threshold':>9} {'vad_floor':>9} {'TPR':>7} {'FPR':>7}  (tp fn fp tn)")
    for row in rows:
        print(f"{row['threshold']:>9} {row['vad_rms_floor']:>9} "
              f"{row['tpr']:>7} {row['fpr']:>7}  "
              f"({row['tp']} {row['fn']} {row['fp']} {row['tn']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
