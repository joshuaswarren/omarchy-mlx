    def test_file_grew_during_write_bounds_reads_and_writes(self) -> None:
        target = self.decision_dir / "model.safetensors"
        expected = target.stat().st_size
        target_ino = target.stat().st_ino
        mutated = False
        reads: list[int] = []
        written: list[int] = []
        real_open = transfer._open_regular
        real_fstat = os.fstat
        real_zip_open = transfer.zipfile.ZipFile.open

        @contextlib.contextmanager
        def counting_open(path, rel=None):
            with real_open(path, rel) as (stream, st):
                opened = path / rel if rel is not None else Path(path)
                track = mutated and opened == target

                class CountingStream:
                    def read(self, n=-1):
                        data = stream.read(n)
                        if track:
                            reads.append(len(data))
                        return data

                yield CountingStream(), st

        def stale_size_fstat(fd):
            st = real_fstat(fd)
            if mutated and st.st_ino == target_ino:
                vals = list(st)
                vals[stat.ST_SIZE] = expected
                return os.stat_result(vals)
            return st

        def counting_zip_open(zf_self, name, mode="r", *args, **kwargs):
            writer = real_zip_open(zf_self, name, mode, *args, **kwargs)
            member = name.filename if isinstance(name, zipfile.ZipInfo) else name
            if mode == "w" and member == "everyday/decision/model.safetensors":
                class CountingWriter:
                    def __enter__(self):
                        writer.__enter__()
                        return self

                    def __exit__(self, *exc):
                        return writer.__exit__(*exc)

                    def write(self, data):
                        written.append(len(data))
                        return writer.write(data)

                return CountingWriter()
            return writer

        def cb(_done, _total, rel):
            nonlocal mutated
            if rel == "everyday/chat/model.safetensors":
                with target.open("ab") as f:
                    f.write(b"X" * (3 << 20))
                mutated = True

        with mock.patch.object(transfer, "_open_regular", counting_open), \
                mock.patch.object(transfer.os, "fstat", side_effect=stale_size_fstat), \
                mock.patch.object(transfer.zipfile.ZipFile, "open", counting_zip_open):
            with self.assertRaisesRegex(transfer.TransferError, "file changed during export"):
                self.export(progress=cb)
        self.assertTrue(mutated)
        self.assertGreater(sum(reads), expected)
        self.assertLessEqual(sum(reads), expected + 1)
        self.assertLessEqual(sum(written), expected)
        self.assertFalse(self.bundle_path().exists())
        self.assertEqual(list(self.root.glob("*.zip.tmp")), [])

