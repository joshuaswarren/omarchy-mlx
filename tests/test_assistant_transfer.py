    def _run_bounded(self, fn, timeout: float = 10.0):
        outcome: dict = {}

        def target():
            try:
                outcome["value"] = fn()
            except BaseException as exc:
                outcome["exc"] = exc

        worker = threading.Thread(target=target, daemon=True)
        worker.start()
        worker.join(timeout)
        self.assertFalse(worker.is_alive(), f"call did not finish within {timeout}s")
        if "exc" in outcome:
            raise outcome["exc"]
        return outcome.get("value")

