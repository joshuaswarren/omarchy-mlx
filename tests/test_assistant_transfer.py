    def test_swapped_model_root_to_fifo_refused_without_hanging(self) -> None:
        nested = self.chat_dir / "a"
        nested.mkdir()
        (nested / "weights.bin").write_bytes(b"W" * 128)

        for label, swap_before in (("before-walk", True), ("between-walk-and-hash", False)):
            with self.subTest(label):
                moved = self.root / f"moved-root-{label}"
                real_walk = transfer._walk_artifact
                swapped = False

                def swap_to_fifo() -> None:
                    nonlocal swapped
                    swapped = True
                    self.chat_dir.rename(moved)
                    os.mkfifo(self.chat_dir)

                def swapping_walk(directory):
                    is_target = not swapped and Path(directory) == self.chat_dir
                    if swap_before and is_target:
                        swap_to_fifo()
                    rels = real_walk(directory)
                    if not swap_before and is_target:
                        swap_to_fifo()
                    return rels

                try:
                    with mock.patch.object(transfer, "_walk_artifact", swapping_walk):
                        expected = (
                            "cannot read artifact directory"
                            if swap_before
                            else "cannot read"
                        )
                        with self.assertRaisesRegex(transfer.TransferError, expected):
                            self._run_bounded(self.export)
                    self.assertTrue(swapped)
                    self.assertFalse(self.bundle_path().exists())
                    self.assertEqual(list(self.root.glob("*.zip.tmp")), [])
                finally:
                    if swapped:
                        if os.path.lexists(self.chat_dir):
                            self.chat_dir.unlink()
                        if moved.exists():
                            moved.rename(self.chat_dir)


