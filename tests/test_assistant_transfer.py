            with mock.patch.object(transfer.os, "fstat", side_effect=small_fstat):
                with self.assertRaisesRegex(transfer.TransferError, "file exceeds"):
                    builder.add_file("everyday/chat/grown.bin", self.root, "grown.bin")
            self.assertGreater(sum(reads), cap)
            self.assertLessEqual(sum(reads), cap + 1)

